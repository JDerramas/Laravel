 *      take effect immediately across all user devices without requiring manual re-login.
 *   3. Strict Portal Access Guards (`require_admin`, `require_teacher`, `require_student_area`):
 *      Prevents unauthorized cross-role tampering and immediately redirects unauthorized visitors
 *      back to their own dedicated portal.
 *   4. Clean JSON API Error Handling: Gracefully emits HTTP 401/403 JSON envelopes for REST requests.
